#!/usr/bin/env node
// The index of published decision records, docs/agent-log/index.json: every record file (.json and its .md twin) in
// docs/agent-log and its folders, by folder. The app's vault and decision pages read it from GitHub first and fetch
// only the files it lists, so they never request a record that does not exist (each miss was a 404 in the browser's
// console). The weekly agent workflow rewrites it when it commits records; CI checks it is current.
//
//   node scripts/agent-log-index.mjs           write docs/agent-log/index.json
//   node scripts/agent-log-index.mjs --check   exit 1 when the committed index differs from the folders
import { readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(fileURLToPath(new URL(".", import.meta.url)), "..");
const DIR = "docs/agent-log";
const OUT = join(ROOT, DIR, "index.json");
const RECORD = /^\d{4}-\d{2}-\d{2}-.+\.(json|md)$/;

/** Folder (repository path) to its record file names, sorted, for every folder that holds records. */
export function buildIndex(root = ROOT) {
  const folders = {};
  const walk = (abs) => {
    const names = readdirSync(abs).sort();
    const files = names.filter((n) => RECORD.test(n) && statSync(join(abs, n)).isFile());
    if (files.length > 0) folders[relative(root, abs).split("\\").join("/")] = files;
    for (const n of names) if (statSync(join(abs, n)).isDirectory()) walk(join(abs, n));
  };
  walk(join(root, DIR));
  return {
    about:
      "Generated by scripts/agent-log-index.mjs: every decision record file in docs/agent-log, by folder. Do not edit by hand.",
    version: 1,
    folders,
  };
}

export const render = (index) => `${JSON.stringify(index, null, 2)}\n`;

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const next = render(buildIndex());
  if (process.argv.includes("--check")) {
    let current = "";
    try {
      current = readFileSync(OUT, "utf8");
    } catch {
      // missing: reported below
    }
    if (current !== next) {
      console.error(`${DIR}/index.json is out of date: run node scripts/agent-log-index.mjs`);
      process.exit(1);
    }
    console.log(`${DIR}/index.json is current`);
  } else {
    writeFileSync(OUT, next);
    const n = Object.values(JSON.parse(next).folders).reduce((s, f) => s + f.length, 0);
    console.log(`wrote ${DIR}/index.json: ${n} files`);
  }
}
